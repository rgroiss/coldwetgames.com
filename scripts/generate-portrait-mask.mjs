import { writeFileSync } from 'node:fs';

// A static silhouette: roughen only the perimeter, never the photograph itself.
const width = 600;
const height = 660;
let seed = 220926;
const random = () => {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 0x100000000;
};

function edge(length, project) {
  const points = [];
  const tears = Array.from({ length: 5 }, () => ({
    position: 30 + random() * (length - 60),
    radius: 8 + random() * 18,
    depth: 3 + random() * 6,
  }));
  let drift = 5;
  for (let distance = 12; distance <= length - 12; distance += 1.5 + random() * 3) {
    drift = drift * .9 + random() * .9;
    const tear = tears.reduce((depth, nick) =>
      depth + Math.max(0, 1 - Math.abs(distance - nick.position) / nick.radius) * nick.depth, 0);
    const inset = 3 + drift + tear + (random() - .5) * 4;
    points.push(project(distance, inset));
  }
  return points;
}

const points = [
  ...edge(width, (position, inset) => [position, inset]),
  ...edge(height, (position, inset) => [width - inset, position]),
  ...edge(width, (position, inset) => [width - position, height - inset]),
  ...edge(height, (position, inset) => [inset, height - position]),
];
const path = points.map(([x, y], index) =>
  `${index ? 'L' : 'M'}${x.toFixed(2)} ${y.toFixed(2)}`).join('\n    ');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" preserveAspectRatio="none">
  <!-- Generated by scripts/generate-portrait-mask.mjs. No filter or image distortion. -->
  <path fill="white" d="${path} Z" />
</svg>
`;
writeFileSync(new URL('../assets/textures/portrait-torn-edge.svg', import.meta.url), svg);
